<?php

declare(strict_types=1);

namespace DH\Auditor\Provider\Doctrine\Auditing\Root;

use DH\Auditor\Exception\InvalidArgumentException;
use DH\Auditor\Exception\MappingException;
use DH\Auditor\Provider\Doctrine\Auditing\Transaction\AuditTrait;
use DH\Auditor\Provider\Doctrine\DoctrineProvider;
use DH\Auditor\Provider\Doctrine\Persistence\Helper\DoctrineHelper;
use DH\Auditor\Tests\Provider\Doctrine\Auditing\Root\RootIdentityTest;
use Doctrine\ORM\EntityManagerInterface;

/**
 * Identifier of an entity as the audit tables store it: the same value as the object_id column, so that the root
 * index, the reader and the templates agree (backed enums, types converted for the audit, identity through a foreign
 * entity).
 *
 * @see RootIdentityTest
 */
final class ObjectIdentifier
{
    use AuditTrait;

    public function __construct(private readonly DoctrineProvider $provider) {}

    /**
     * Returns the identifier of $entity, or null when it has none yet (generated by the flush).
     *
     * @throws InvalidArgumentException when an identifier value cannot be written as a string
     */
    public function identify(EntityManagerInterface $entityManager, object $entity): ?string
    {
        try {
            return $this->string($this->id($entityManager, $entity), $entity);
        } catch (MappingException) {
            // composite primary key: not audited, but such an entity can be a root
        }

        $identifier = $entityManager->getUnitOfWork()->isInIdentityMap($entity)
            ? $entityManager->getUnitOfWork()->getEntityIdentifier($entity)
            : $entityManager->getClassMetadata(DoctrineHelper::getRealClassName($entity))->getIdentifierValues($entity);

        $parts = [];
        foreach ($identifier as $value) {
            $part = $this->string($value instanceof \BackedEnum ? $value->value : $value, $entity);
            if (null === $part) {
                return null;
            }

            $parts[] = $part;
        }

        return [] === $parts ? null : implode('-', $parts);
    }

    private function string(mixed $id, object $entity): ?string
    {
        if (null === $id || '' === $id) {
            return null;
        }

        if (\is_scalar($id) || $id instanceof \Stringable) {
            return (string) $id;
        }

        throw new InvalidArgumentException(\sprintf('The identifier of "%s" cannot be written as a string (%s).', DoctrineHelper::getRealClassName($entity), get_debug_type($id)));
    }
}
