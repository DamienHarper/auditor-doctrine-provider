<?php

declare(strict_types=1);

namespace DH\Auditor\Provider\Doctrine\Auditing\Root;

/**
 * A root an audited entity belongs to, collected when the flush starts.
 *
 * The identifier of a root inserted by the same flush is only known once it is written: it is read from $root when
 * the audit entries are written. The identifier of a root that already exists is captured right away, since Doctrine
 * resets the generated identifier of an entity deleted by the flush.
 *
 * @internal
 */
final readonly class RootReference
{
    /**
     * @param string      $path  path (or resolver key) that led to the root, such as "property" or "visit.property"
     * @param string      $class FQCN of the root, the root class of its inheritance hierarchy
     * @param null|string $id    identifier of the root when it was known, null when it is generated by the flush
     */
    public function __construct(
        public string $path,
        public string $class,
        public object $root,
        public ?string $id,
    ) {}

    public function key(): string
    {
        return $this->path."\0".$this->class."\0".($this->id ?? '#'.spl_object_id($this->root));
    }
}
